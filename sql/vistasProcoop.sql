    dbo.SERSOC.NUMERO,
    dbo.SERSOC.PISO,
    dbo.SERSOC.DPTO,
    dbo.SERSOC.COD_LOC,
    dbo.LOCALIDA.DES_LOC AS NOMBRELOCALIDAD,
    dbo.SERSOC.COD_POS,
    dbo.SERSOC.CAT_CIR,
    dbo.SERSOC.CAT_LOT,
    dbo.SERSOC.CAT_MAN,
    dbo.SERSOC.CAT_PAR,
    dbo.SERSOC.CAT_PH,
    dbo.SERSOC.GUIA,
    dbo.SERSOC.NOM_GUIA,
    dbo.SERSOC.COD_PRO,
    dbo.PROVINC.DES_PRO AS PROVINCIA,
    dbo.SERSOC.ALTA_ADM,
