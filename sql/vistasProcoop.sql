SELECT
    dbo.PERSONAS.TIP_PERSO,
    dbo.PERSONAS.COD_PER,
    dbo.PERSONAS.TIP_DNI,
    dbo.PERSONAS.NUM_DNI,
    dbo.PERSONAS.APELLIDOS,
    dbo.PERSONAS.SEXO,
    dbo.PERSONAS.CIVIL,
    dbo.PERSONAS.COD_CAL,
    dbo.CALLES.DES_CAL AS NOMBRECALLE,
    dbo.PERSONAS.NUMERO,
    dbo.PERSONAS.PISO,
    dbo.PERSONAS.DPTO,
    dbo.LOCALIDA.DES_LOC AS NOMBRELOCALIDAD,
    dbo.PERSONAS.FEC_NAC,
    dbo.PERSONAS.TELEFONO,
    dbo.PERSONAS.FAX,
    dbo.PERSONAS.COD_POS,
    dbo.PERSONAS.COD_PRO,
    dbo.PROVINC.DES_PRO AS PROVINCIA,
    dbo.PERSONAS.EMAIL,
    dbo.PERSONAS.GRU_SGR,
    dbo.PERSONAS.FAC_SGR,
    dbo.PERSONAS.DAD_SGR,
    dbo.PERSONAS.COD_SIT,
    dbo.SITIVA.DES_SIT AS DESCRI_SITIVA,
    dbo.PERSONAS.FEC_ALTA,
    dbo.SOCIOS.cod_soc,
    dbo.SOCIOS.cuit,
    dbo.SOCIOS.activo,
    dbo.SOCIOS.alta,
    dbo.SOCIOS.baja,
    dbo.SOCIOS.clave_web
FROM
    dbo.PERSONAS
    LEFT OUTER JOIN dbo.SOCIOS ON dbo.SOCIOS.cod_per = dbo.PERSONAS.COD_PER
    LEFT OUTER JOIN dbo.[DOCUMENT] ON dbo.[DOCUMENT].COD_DOC = dbo.PERSONAS.TIP_DNI
    LEFT OUTER JOIN dbo.EST_CIVIL ON dbo.EST_CIVIL.COD_CIVIL = dbo.PERSONAS.CIVIL
    LEFT OUTER JOIN dbo.CALLES ON dbo.CALLES.COD_CAL = dbo.PERSONAS.COD_CAL
    LEFT OUTER JOIN dbo.LOCALIDA ON dbo.LOCALIDA.COD_LOC = dbo.PERSONAS.COD_LOC
    LEFT OUTER JOIN dbo.PROVINC ON dbo.PROVINC.COD_PRO = dbo.PERSONAS.COD_PRO
    LEFT OUTER JOIN dbo.SITIVA ON dbo.SITIVA.COD_SIT = dbo.PERSONAS.COD_SIT
    
