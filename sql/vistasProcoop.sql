    LEFT OUTER JOIN dbo.LOCALIDA ON dbo.LOCALIDA.COD_LOC = dbo.SERSOC.COD_LOC
    LEFT OUTER JOIN dbo.PROVINC ON dbo.SERSOC.COD_PRO = dbo.PROVINC.COD_PRO
    LEFT OUTER JOIN dbo.PROFESIO ON dbo.PROFESIO.COD_PROF = dbo.SERSOC.COD_PROF
    
